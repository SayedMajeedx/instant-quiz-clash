const DICTS: Record<Lang, Dict> = { en, ar };

type Ctx = {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (lang: Lang) => void;
  toggle: () => void;
  t: (key: keyof typeof en | string, vars?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<Ctx | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang] = useState<Lang>("ar");

  useEffect(() => {
    document.documentElement.lang = "ar";
    document.documentElement.dir = "rtl";
    window.localStorage.setItem(STORAGE_KEY, "ar");
  }, []);

  const value = useMemo<Ctx>(
    () => ({
      lang: "ar",
      dir: "rtl",
      setLang: () => {},
      toggle: () => {},
      t: (key, vars) => interpolate(ar[key as string] ?? en[key as string] ?? (key as string), vars),
    }),
    [],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      lang: "ar",
      dir: "rtl",
      setLang: () => {},
      toggle: () => {},
      t: (key, vars) => interpolate(ar[key as string] ?? en[key as string] ?? (key as string), vars),
    };
  }
  return ctx;
}

